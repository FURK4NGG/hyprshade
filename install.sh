#!/usr/bin/env bash
set -Eeuo pipefail

APP_NAME="Hyprshade Night Screen"
PROJECT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

SCRIPT_SRC="$PROJECT_DIR/hyprshade-auto.sh"
OVERLAY_SRC="$PROJECT_DIR/night-screen-overlay.py"
SCRIPT_DIR="$HOME/.local/bin"
SCRIPT_DST="$SCRIPT_DIR/hyprshade-auto.sh"
OVERLAY_DST="$SCRIPT_DIR/night-screen-overlay.py"

STATE_DIR="$HOME/.config/scripts"
STATE_FILE="$STATE_DIR/hyprshade-toggle-state"

USER_SYSTEMD_DIR="$HOME/.config/systemd/user"
SERVICE_SRC="$PROJECT_DIR/hyprshade-auto.service"
TIMER_SRC="$PROJECT_DIR/hyprshade-auto.timer"
SERVICE_DST="$USER_SYSTEMD_DIR/hyprshade-auto.service"
TIMER_DST="$USER_SYSTEMD_DIR/hyprshade-auto.timer"

SHADER_NAME="night_screen.frag"
SHADER_DIR="$HOME/.config/hypr/shaders"
SHADER_SRC=""

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BLUE='\033[0;34m'
RESET='\033[0m'

step() { printf "\n${BLUE}==>${RESET} %s\n" "$*"; }
ok()   { printf "${GREEN}[OK]${RESET} %s\n" "$*"; }
warn() { printf "${YELLOW}[WARNING]${RESET} %s\n" "$*"; }
err()  { printf "${RED}[ERROR]${RESET} %s\n" "$*" >&2; }
die()  { err "$*"; exit 1; }

trap 'rc=$?; err "Installation stopped (line: $LINENO, exit code: $rc)."; exit "$rc"' ERR

printf '%s\n' \
    '====================================' \
    "  $APP_NAME Installer (Arch Linux)" \
    '===================================='

step "Checking source files"

command -v pacman >/dev/null 2>&1 ||
    die "pacman was not found. This installer is intended for Arch Linux."

[[ -f "$SCRIPT_SRC" ]] ||
    die "hyprshade-auto.sh was not found in the repository: $SCRIPT_SRC"

[[ -f "$OVERLAY_SRC" ]] ||
    die "night-screen-overlay.py was not found in the repository: $OVERLAY_SRC"

# Do not generate service/timer files. If they are not in the repository,
# the installer will skip timer setup rather than creating its own files.
if [[ -f "$PROJECT_DIR/$SHADER_NAME" ]]; then
    SHADER_SRC="$PROJECT_DIR/$SHADER_NAME"
elif [[ -f "$PROJECT_DIR/shaders/$SHADER_NAME" ]]; then
    SHADER_SRC="$PROJECT_DIR/shaders/$SHADER_NAME"
fi

ok "hyprshade-auto.sh ve night-screen-overlay.py bulundu."

step "Installing required packages"

sudo pacman -S --needed python python-pip python-pipx curl unzip

step "Checking Hyprshade"

export PATH="$HOME/.local/bin:$HOME/.local/pipx/bin:$PATH"

if ! command -v hyprshade >/dev/null 2>&1; then
    warn "Hyprshade was not found; version 4.0.1 will be installed using pipx."

    TMP_DIR="$(mktemp -d)"
    trap 'rc=$?; rm -rf "${TMP_DIR:-}"; if (( rc != 0 )); then err "Installation stopped (line: $LINENO, exit code: $rc)."; fi; exit "$rc"' EXIT

    HYPRSHADE_URL="https://github.com/loqusion/hyprshade/archive/refs/tags/4.0.1.zip"
    curl -fL "$HYPRSHADE_URL" -o "$TMP_DIR/hyprshade-4.0.1.zip"
    unzip -q "$TMP_DIR/hyprshade-4.0.1.zip" -d "$TMP_DIR"

    HYPRSHADE_SOURCE="$TMP_DIR/hyprshade-4.0.1"
    [[ -d "$HYPRSHADE_SOURCE" ]] ||
        die "The downloaded archive does not contain the hyprshade-4.0.1 directory."

    pipx install "$HYPRSHADE_SOURCE"
    export PATH="$HOME/.local/bin:$HOME/.local/pipx/bin:$PATH"
fi

command -v hyprshade >/dev/null 2>&1 ||
    die "Hyprshade was not found on PATH."

VERSION_OUTPUT="$(hyprshade --version 2>&1)"
printf '%s\n' "$VERSION_OUTPUT"
ok "Hyprshade is available."

step "Installing repository files (overwrite existing files)"

mkdir -p "$SCRIPT_DIR" "$STATE_DIR" "$SHADER_DIR"

# Copy only files that already exist in the repository; overwrite destinations.
install -m 755 "$SCRIPT_SRC" "$SCRIPT_DST"
install -m 755 "$OVERLAY_SRC" "$OVERLAY_DST"

bash -n "$SCRIPT_DST"
ok "Installed: $SCRIPT_DST"
ok "Installed: $OVERLAY_DST"

if [[ -n "$SHADER_SRC" ]]; then
    install -m 644 "$SHADER_SRC" "$SHADER_DIR/$SHADER_NAME"
    ok "Installed shader: $SHADER_DIR/$SHADER_NAME"
else
    warn "$SHADER_NAME was not found in the repository; no shader file was created."
fi

step "Applying permissions"

# Match the requested permissions without making files root-owned.
if compgen -G "$STATE_DIR/*.sh" >/dev/null; then
    find "$STATE_DIR" -maxdepth 1 -type f -name '*.sh' -exec chmod +x {} +
fi

chmod +x "$SCRIPT_DST"
chmod +x "$OVERLAY_DST"

# The state file is generated by the toggle script at runtime. Do not create it here.
if [[ -f "$STATE_FILE" ]]; then
    chmod 600 "$STATE_FILE"
    chown "$USER:$(id -gn)" "$STATE_FILE"
    ok "Preserved existing state file and applied mode 600: $STATE_FILE"
else
    ok "State file will be generated by hyprshade-auto.sh when first needed."
fi

step "Installing existing systemd files"

mkdir -p "$USER_SYSTEMD_DIR"
SYSTEMD_FILES_INSTALLED=0

if [[ -f "$SERVICE_SRC" ]]; then
    install -m 644 "$SERVICE_SRC" "$SERVICE_DST"
    ok "Installed existing service: $SERVICE_DST"
    SYSTEMD_FILES_INSTALLED=1
else
    warn "hyprshade-auto.service was not found in the repository; no file was created."
fi

if [[ -f "$TIMER_SRC" ]]; then
    install -m 644 "$TIMER_SRC" "$TIMER_DST"
    ok "Installed existing timer: $TIMER_DST"
    SYSTEMD_FILES_INSTALLED=1
else
    warn "hyprshade-auto.timer was not found in the repository; no file was created."
fi

if [[ -f "$SERVICE_DST" && -f "$TIMER_DST" ]]; then
    systemctl --user daemon-reload
    systemctl --user enable --now hyprshade-auto.timer
    ok "hyprshade-auto.timer has been enabled."
else
    warn "The timer was not enabled because both the service and timer files are not available. The installer does not create these files."
fi

printf '\n====================================\n'
printf "${GREEN}Installation completed.${RESET}\n"
printf 'Hyprshade: %s\n' "$VERSION_OUTPUT"
printf 'Toggle native hyprland: %s\n' "$SCRIPT_DST backend native"
printf 'Toggle screen overlay: %s\n' "$SCRIPT_DST backend overlay"
printf 'Toggle script: %s\n' "$SCRIPT_DST"
printf 'State file (runtime-generated): %s\n' "$STATE_FILE"
printf '====================================\n'
